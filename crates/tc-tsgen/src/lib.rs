//! TypeScript generation from a `tc_wire` [`Schema`].
//!
//! Walks a [`Schema`] and writes TypeScript types plus codecs that match the
//! Rust encoding byte for byte. Mapping:
//!
//! | Rust | TypeScript |
//! | ---- | ---------- |
//! | `u8`, `u16`, `u32`, `i32`, `u64`, `i64` | `number` (64-bit: safe integers only) |
//! | `Fixed` | the runtime's `Fixed` class: exact `bigint` bits |
//! | `bool` | `boolean` |
//! | `String` | `string` |
//! | `Vec<T>` | `T[]` |
//! | `Option<T>` | `T \| null` |
//! | `BTreeMap<K, V>` | `Map<K, V>`, iterating in key order |
//! | `Bytes` | `Uint8Array` |
//! | struct | `interface`, camelCase field names |
//! | newtype | `type X = Inner` |
//! | enum | union discriminated by `type` (the variant name); a tuple variant's value is `value` |
//!
//! Besides types and codecs, the generated module holds `SCHEMA_HASH`, the
//! [`Config`]'s constants, `TYPES` (the schema as data, what a patch
//! applier walks), and `api`: one descriptor per live query with its wire
//! name, argument encoder, and result codec. An optional [`SdkConfig`] adds
//! a client SDK's pass-through events for one root message enum.
//!
//! Everything a game names is configuration: the header, the runtime
//! imports, the constants, the reserved names and the SDK's event lists. A
//! game's own generator builds a [`Config`] and writes [`generate`]'s files.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use tc_wire::{Field, QueryDef, Schema, TypeDef, TypeKind, TypeRef, Variant, VariantFields};

mod sdk;

pub use sdk::{Pass, Payload, SdkConfig};

/// Names the generated module imports or exports besides the schema's types.
pub const RESERVED: &[&str] = &[
    "Reader",
    "Writer",
    "DecodeError",
    "Fixed",
    "Uint8Array",
    "ArrayBuffer",
    "Map",
    "MapKey",
    "TypeRef",
    "TypeShape",
    "Types",
    "QueryApi",
    "PatchError",
];

/// A constant exported beside the schema (not part of its hash): a rule
/// the server and its clients share.
#[derive(Debug, Clone)]
pub struct Constant {
    /// The exported name.
    pub name: String,
    /// Its doc comment (one line).
    pub doc: String,
    /// Its TypeScript value, as written.
    pub value: String,
}

/// What a game names in its generated TypeScript.
#[derive(Debug, Clone)]
pub struct Config {
    /// The first line(s) of every generated file, each ending in `\n`.
    pub header: String,
    /// The generated module's path, relative to the output root.
    pub generated_path: String,
    /// The module exporting `Reader`, `Writer`, `invalidVariant` and `Fixed`.
    pub wire_import: String,
    /// The module exporting the types `QueryApi`, `TypeRef` and `Types`.
    pub patch_import: String,
    /// The doc of `SCHEMA_HASH`.
    pub hash_doc: String,
    /// Constants exported after `SCHEMA_HASH`, in order.
    pub constants: Vec<Constant>,
    /// Names the generated module must not declare, besides [`RESERVED`].
    pub reserved: Vec<String>,
    /// The client SDK's events, if the game generates them.
    pub sdk: Option<SdkConfig>,
}

impl Default for Config {
    fn default() -> Self {
        Self {
            header: "// Generated by tc-tsgen from the Rust protocol types. Do not edit.\n".into(),
            generated_path: "generated.ts".into(),
            wire_import: "./wire.ts".into(),
            patch_import: "./patch.ts".into(),
            hash_doc:
                "Hash of the protocol schema: a client and server agree on it before they talk."
                    .into(),
            constants: Vec::new(),
            reserved: Vec::new(),
            sdk: None,
        }
    }
}

/// Generates the TypeScript for `schema` as `(path relative to the output
/// root, contents)`: the generated module, then the SDK's files if
/// configured. An error names a name collision or an SDK list mismatch.
pub fn generate(schema: &Schema, config: &Config) -> Result<Vec<(String, String)>, String> {
    let mut files = vec![(config.generated_path.clone(), generated_ts(schema, config)?)];
    if let Some(sdk) = &config.sdk {
        files.extend(sdk::files(schema, config, sdk)?);
    }
    Ok(files)
}

/// The generated module alone: types, codecs, `TYPES` and `api`.
pub fn generated_ts(schema: &Schema, config: &Config) -> Result<String, String> {
    check(schema, config)?;
    Ok(module_ts(schema, config))
}

/// A query's TypeScript name: its wire name in camelCase.
pub fn ts_query_name(name: &str) -> String {
    ts_field_name(name)
}

/// The name of a query's TypeScript argument type: `storage_view` gives
/// `StorageViewArgs`.
pub fn ts_args_name(name: &str) -> String {
    let camel = ts_field_name(name);
    let mut chars = camel.chars();
    match chars.next() {
        Some(first) => format!("{}{}Args", first.to_uppercase(), chars.as_str()),
        None => "Args".into(),
    }
}

/// A type reference as the JSON data `patch.ts` walks: scalars are their
/// Rust names (`"u32"`, `"Fixed"`, `"String"`, `"Bytes"`), and containers
/// are `{"vec": T}`, `{"option": T}`, `{"map": [K, V]}`, `{"named": "X"}`.
pub fn ts_type_ref(ty: &TypeRef) -> String {
    match ty {
        TypeRef::Vec(inner) => format!("{{\"vec\": {}}}", ts_type_ref(inner)),
        TypeRef::Option(inner) => format!("{{\"option\": {}}}", ts_type_ref(inner)),
        TypeRef::Map(key, value) => {
            format!(
                "{{\"map\": [{}, {}]}}",
                ts_type_ref(key),
                ts_type_ref(value)
            )
        }
        TypeRef::Named(name) => format!("{{\"named\": \"{name}\"}}"),
        scalar => format!("\"{scalar}\""),
    }
}

/// A named type's shape as `patch.ts` data: `{"struct": [field types]}`,
/// `{"newtype": T}`, or `{"enum": [[variant field types], ...]}`.
fn ts_type_shape(kind: &TypeKind) -> String {
    let list = |types: Vec<&TypeRef>| {
        let inner: Vec<String> = types.into_iter().map(ts_type_ref).collect();
        format!("[{}]", inner.join(", "))
    };
    match kind {
        TypeKind::Struct(fields) => {
            format!(
                "{{\"struct\": {}}}",
                list(fields.iter().map(|f| &f.ty).collect())
            )
        }
        TypeKind::Newtype(inner) => format!("{{\"newtype\": {}}}", ts_type_ref(inner)),
        TypeKind::Enum(variants) => {
            let inner: Vec<String> = variants
                .iter()
                .map(|v| match &v.fields {
                    VariantFields::Unit => list(vec![]),
                    VariantFields::Named(fields) => list(fields.iter().map(|f| &f.ty).collect()),
                    VariantFields::Newtype(inner) => list(vec![inner]),
                })
                .collect();
            format!("{{\"enum\": [{}]}}", inner.join(", "))
        }
    }
}

/// The TypeScript property name for a Rust field name: snake_case to camelCase.
pub fn ts_field_name(rust_name: &str) -> String {
    let mut out = String::with_capacity(rust_name.len());
    let mut upper = false;
    for c in rust_name.chars() {
        if c == '_' && !out.is_empty() {
            upper = true;
        } else if upper {
            out.extend(c.to_uppercase());
            upper = false;
        } else {
            out.push(c);
        }
    }
    out
}

fn check(schema: &Schema, config: &Config) -> Result<(), String> {
    let reserved =
        |name: &str| RESERVED.contains(&name) || config.reserved.iter().any(|r| r == name);
    let mut query_names = BTreeSet::new();
    for query in schema.queries() {
        let args = ts_args_name(query.name);
        if schema.get(&args).is_some() || reserved(&args) {
            return Err(format!(
                "query `{}`: its argument type `{args}` collides with another name; rename one",
                query.name
            ));
        }
        if !query_names.insert(ts_query_name(query.name)) {
            return Err(format!(
                "query `{}`: two queries map to the TypeScript name `{}`",
                query.name,
                ts_query_name(query.name)
            ));
        }
        let mut seen = BTreeSet::new();
        for field in &query.args {
            if !seen.insert(ts_field_name(field.name)) {
                return Err(format!(
                    "query `{}`: two arguments map to the TypeScript name `{}`",
                    query.name,
                    ts_field_name(field.name)
                ));
            }
        }
    }
    for def in schema.types() {
        if reserved(def.name) {
            return Err(format!(
                "protocol type `{}` collides with a name the TypeScript runtime uses; rename it",
                def.name
            ));
        }
        let fields: Vec<(String, &[Field])> = match &def.kind {
            TypeKind::Struct(fields) => vec![(def.name.to_string(), fields)],
            TypeKind::Newtype(_) => vec![],
            TypeKind::Enum(variants) => variants
                .iter()
                .filter_map(|v| match &v.fields {
                    VariantFields::Named(fields) => {
                        Some((format!("{}::{}", def.name, v.name), fields.as_slice()))
                    }
                    _ => None,
                })
                .collect(),
        };
        let is_enum = matches!(def.kind, TypeKind::Enum(_));
        for (context, fields) in fields {
            let mut seen = BTreeSet::new();
            for field in fields {
                let name = ts_field_name(field.name);
                if is_enum && name == "type" {
                    return Err(format!(
                        "{context}.{}: a variant field named `type` collides with the discriminant",
                        field.name
                    ));
                }
                if !seen.insert(name.clone()) {
                    return Err(format!(
                        "{context}: two fields map to the TypeScript name `{name}`"
                    ));
                }
            }
        }
    }
    Ok(())
}

fn module_ts(schema: &Schema, config: &Config) -> String {
    let mut out = String::new();
    out.push_str(&config.header);
    let _ = writeln!(
        out,
        "\nimport {{ Reader, Writer, invalidVariant, type Fixed }} from \"{}\";",
        config.wire_import
    );
    let _ = writeln!(
        out,
        "import type {{ QueryApi, TypeRef, Types }} from \"{}\";\n",
        config.patch_import
    );
    let _ = writeln!(out, "/** {} */", config.hash_doc);
    let _ = writeln!(out, "export const SCHEMA_HASH = \"{}\";", schema.hash());
    for constant in &config.constants {
        let _ = writeln!(out, "/** {} */", constant.doc);
        let _ = writeln!(out, "export const {} = {};", constant.name, constant.value);
    }
    out.push_str("\n// Types\n");
    for def in schema.types() {
        out.push('\n');
        type_decl(&mut out, def);
    }

    out.push_str("\n// Message codecs\n");
    for root in schema.roots() {
        let _ = write!(
            out,
            "\n/** Encodes one `{root}` frame. Throws if a value is out of range. */\n\
             export function encode{root}(msg: {root}): Uint8Array {{\n\
             \x20 const w = new Writer();\n\
             \x20 write{root}(w, msg);\n\
             \x20 return w.finish();\n\
             }}\n\
             \n\
             /** Decodes one `{root}` frame. Throws `DecodeError` on any malformed input. */\n\
             export function decode{root}(bytes: Uint8Array | ArrayBuffer): {root} {{\n\
             \x20 const r = new Reader(bytes);\n\
             \x20 const msg = read{root}(r);\n\
             \x20 r.finish();\n\
             \x20 return msg;\n\
             }}\n"
        );
    }

    out.push_str("\n// Type codecs\n");
    for def in schema.types() {
        out.push('\n');
        write_fn(&mut out, def);
        out.push('\n');
        read_fn(&mut out, def);
    }

    out.push_str("\n// Schema as data, for applying patches (see patch.ts)\n\n");
    out.push_str("/** Every named type's shape, by name. */\n");
    out.push_str("export const TYPES: Types = {\n");
    for def in schema.types() {
        let _ = writeln!(out, "  {}: {},", def.name, ts_type_shape(&def.kind));
    }
    out.push_str("};\n");

    out.push_str("\n// Live queries\n");
    for query in schema.queries() {
        out.push('\n');
        args_decl(&mut out, query);
    }
    out.push_str(QUERY_HELPER);
    out.push_str(
        "/** The live queries: subscribe with `Subscribe { query: name, args: encodeArgs(args) }`. */\n",
    );
    out.push_str("export const api = {\n");
    for query in schema.queries() {
        api_entry(&mut out, query);
    }
    out.push_str("} as const;\n");
    out
}

const QUERY_HELPER: &str = "
function query<A, R>(
  name: string,
  player: boolean,
  result: TypeRef,
  writeArgs: (w: Writer, args: A) => void,
  readResult: (r: Reader) => R,
  writeResult: (w: Writer, value: R) => void,
): QueryApi<A, R> {
  return {
    name,
    player,
    result,
    encodeArgs(args) {
      const w = new Writer();
      writeArgs(w, args);
      return w.finish();
    },
    decodeResult(bytes) {
      const r = new Reader(bytes);
      const value = readResult(r);
      r.finish();
      return value;
    },
    encodeResult(value) {
      const w = new Writer();
      writeResult(w, value);
      return w.finish();
    },
  };
}

";

fn args_decl(out: &mut String, query: &QueryDef) {
    let name = ts_args_name(query.name);
    let _ = writeln!(out, "/** Arguments of the `{}` query. */", query.name);
    if query.args.is_empty() {
        let _ = writeln!(out, "export type {name} = Record<string, never>;");
    } else {
        let _ = writeln!(out, "export interface {name} {{");
        field_lines(out, "  ", &query.args);
        out.push_str("}\n");
    }
}

fn api_entry(out: &mut String, query: &QueryDef) {
    doc_comment(out, "  ", query.doc);
    let args = ts_args_name(query.name);
    let result = ts_type(&query.result);
    let _ = writeln!(
        out,
        "  {}: query<{args}, {result}>(",
        ts_query_name(query.name)
    );
    let _ = writeln!(out, "    \"{}\",", query.name);
    let _ = writeln!(out, "    {},", query.player);
    let _ = writeln!(out, "    {},", ts_type_ref(&query.result));
    if query.args.is_empty() {
        out.push_str("    () => {},\n");
    } else {
        out.push_str("    (w, a) => {\n");
        for field in &query.args {
            let value = format!("a.{}", ts_field_name(field.name));
            let _ = writeln!(out, "      {};", write_expr(&field.ty, &value, 0));
        }
        out.push_str("    },\n");
    }
    let _ = writeln!(out, "    (r) => {},", read_expr(&query.result));
    let _ = writeln!(out, "    (w, v) => {},", write_expr(&query.result, "v", 0));
    out.push_str("  ),\n");
}

fn doc_comment(out: &mut String, indent: &str, doc: &str) {
    if doc.is_empty() {
        return;
    }
    let doc = doc.replace("*/", "*\\/");
    let lines: Vec<&str> = doc.lines().collect();
    if let [line] = lines.as_slice() {
        let _ = writeln!(out, "{indent}/** {line} */");
        return;
    }
    let _ = writeln!(out, "{indent}/**");
    for line in lines {
        if line.is_empty() {
            let _ = writeln!(out, "{indent} *");
        } else {
            let _ = writeln!(out, "{indent} * {line}");
        }
    }
    let _ = writeln!(out, "{indent} */");
}

fn ts_type(ty: &TypeRef) -> String {
    match ty {
        TypeRef::Bool => "boolean".into(),
        TypeRef::U8 | TypeRef::U16 | TypeRef::U32 | TypeRef::U64 | TypeRef::I32 | TypeRef::I64 => {
            "number".into()
        }
        TypeRef::Fixed => "Fixed".into(),
        TypeRef::String => "string".into(),
        TypeRef::Bytes => "Uint8Array".into(),
        TypeRef::Vec(inner) => match **inner {
            TypeRef::Option(_) => format!("({})[]", ts_type(inner)),
            _ => format!("{}[]", ts_type(inner)),
        },
        TypeRef::Map(key, value) => format!("Map<{}, {}>", ts_type(key), ts_type(value)),
        TypeRef::Option(inner) => format!("{} | null", ts_type(inner)),
        TypeRef::Named(name) => (*name).into(),
    }
}

/// A trailing `// u32`-style comment where `number` hides the Rust type.
fn rust_type_note(ty: &TypeRef) -> String {
    fn has_int(ty: &TypeRef) -> bool {
        match ty {
            TypeRef::U8
            | TypeRef::U16
            | TypeRef::U32
            | TypeRef::U64
            | TypeRef::I32
            | TypeRef::I64 => true,
            TypeRef::Vec(inner) | TypeRef::Option(inner) => has_int(inner),
            TypeRef::Map(key, value) => has_int(key) || has_int(value),
            _ => false,
        }
    }
    if has_int(ty) {
        format!(" // {ty}")
    } else {
        String::new()
    }
}

fn field_lines(out: &mut String, indent: &str, fields: &[Field]) {
    for field in fields {
        doc_comment(out, indent, field.doc);
        let _ = writeln!(
            out,
            "{indent}{}: {};{}",
            ts_field_name(field.name),
            ts_type(&field.ty),
            rust_type_note(&field.ty)
        );
    }
}

fn type_decl(out: &mut String, def: &TypeDef) {
    doc_comment(out, "", def.doc);
    let name = def.name;
    match &def.kind {
        TypeKind::Struct(fields) => {
            let _ = writeln!(out, "export interface {name} {{");
            field_lines(out, "  ", fields);
            out.push_str("}\n");
        }
        TypeKind::Newtype(inner) => {
            let _ = writeln!(
                out,
                "export type {name} = {};{}",
                ts_type(inner),
                rust_type_note(inner)
            );
        }
        TypeKind::Enum(variants) => {
            let _ = writeln!(out, "export type {name} =");
            for (i, variant) in variants.iter().enumerate() {
                variant_decl(out, variant);
                if i + 1 == variants.len() {
                    // Terminate the union on the last member's closing line.
                    out.pop();
                    out.push_str(";\n");
                }
            }
        }
    }
}

fn variant_decl(out: &mut String, variant: &Variant) {
    doc_comment(out, "  ", variant.doc);
    let tag = variant.name;
    match &variant.fields {
        VariantFields::Unit => {
            let _ = writeln!(out, "  | {{ type: \"{tag}\" }}");
        }
        VariantFields::Newtype(inner) => {
            let _ = writeln!(
                out,
                "  | {{ type: \"{tag}\"; value: {} }}{}",
                ts_type(inner),
                rust_type_note(inner)
            );
        }
        VariantFields::Named(fields) if fields.is_empty() => {
            let _ = writeln!(out, "  | {{ type: \"{tag}\" }}");
        }
        VariantFields::Named(fields) => {
            let _ = writeln!(out, "  | {{");
            let _ = writeln!(out, "      type: \"{tag}\";");
            field_lines(out, "      ", fields);
            let _ = writeln!(out, "    }}");
        }
    }
}

/// A statement writing `value` of type `ty` (no trailing semicolon).
fn write_expr(ty: &TypeRef, value: &str, depth: usize) -> String {
    match ty {
        TypeRef::Bool => format!("w.bool({value})"),
        TypeRef::U8 => format!("w.u8({value})"),
        TypeRef::U16 => format!("w.u16({value})"),
        TypeRef::U32 => format!("w.u32({value})"),
        TypeRef::U64 => format!("w.u64({value})"),
        TypeRef::I32 => format!("w.i32({value})"),
        TypeRef::I64 => format!("w.i64({value})"),
        TypeRef::Fixed => format!("w.fixed({value})"),
        TypeRef::String => format!("w.string({value})"),
        TypeRef::Bytes => format!("w.bytes({value})"),
        TypeRef::Named(name) => format!("write{name}(w, {value})"),
        TypeRef::Map(key, val) => {
            let (k, x) = (key_var(depth), item_var(depth));
            format!(
                "w.map({value}, ({k}) => {}, ({x}) => {})",
                write_expr(key, &k, depth + 1),
                write_expr(val, &x, depth + 1)
            )
        }
        TypeRef::Vec(inner) => {
            let x = item_var(depth);
            format!(
                "w.vec({value}, ({x}) => {})",
                write_expr(inner, &x, depth + 1)
            )
        }
        TypeRef::Option(inner) => {
            let x = item_var(depth);
            format!(
                "w.option({value}, ({x}) => {})",
                write_expr(inner, &x, depth + 1)
            )
        }
    }
}

fn key_var(depth: usize) -> String {
    match depth {
        0 => "k".into(),
        n => format!("k{n}"),
    }
}

fn item_var(depth: usize) -> String {
    match depth {
        0 => "x".into(),
        n => format!("x{n}"),
    }
}

/// An expression reading a value of type `ty`.
fn read_expr(ty: &TypeRef) -> String {
    match ty {
        TypeRef::Bool => "r.bool()".into(),
        TypeRef::U8 => "r.u8()".into(),
        TypeRef::U16 => "r.u16()".into(),
        TypeRef::U32 => "r.u32()".into(),
        TypeRef::U64 => "r.u64()".into(),
        TypeRef::I32 => "r.i32()".into(),
        TypeRef::I64 => "r.i64()".into(),
        TypeRef::Fixed => "r.fixed()".into(),
        TypeRef::String => "r.string()".into(),
        TypeRef::Bytes => "r.bytes()".into(),
        TypeRef::Named(name) => format!("read{name}(r)"),
        TypeRef::Map(key, value) => {
            format!(
                "r.map(() => {}, () => {})",
                read_expr(key),
                read_expr(value)
            )
        }
        TypeRef::Vec(inner) => format!("r.vec(() => {})", read_expr(inner)),
        TypeRef::Option(inner) => format!("r.option(() => {})", read_expr(inner)),
    }
}

fn write_fn(out: &mut String, def: &TypeDef) {
    let name = def.name;
    let _ = writeln!(out, "function write{name}(w: Writer, v: {name}): void {{");
    match &def.kind {
        TypeKind::Struct(fields) => {
            for field in fields {
                let value = format!("v.{}", ts_field_name(field.name));
                let _ = writeln!(out, "  {};", write_expr(&field.ty, &value, 0));
            }
        }
        TypeKind::Newtype(inner) => {
            let _ = writeln!(out, "  {};", write_expr(inner, "v", 0));
        }
        TypeKind::Enum(variants) => {
            out.push_str("  switch (v.type) {\n");
            for (index, variant) in variants.iter().enumerate() {
                let _ = writeln!(out, "    case \"{}\":", variant.name);
                let _ = writeln!(out, "      w.variant({index});");
                match &variant.fields {
                    VariantFields::Unit => {}
                    VariantFields::Newtype(inner) => {
                        let _ = writeln!(out, "      {};", write_expr(inner, "v.value", 0));
                    }
                    VariantFields::Named(fields) => {
                        for field in fields {
                            let value = format!("v.{}", ts_field_name(field.name));
                            let _ = writeln!(out, "      {};", write_expr(&field.ty, &value, 0));
                        }
                    }
                }
                out.push_str("      return;\n");
            }
            out.push_str("    default:\n");
            // A one-variant enum isn't a union: TypeScript doesn't narrow
            // it to `never` past its one case.
            let v = if variants.len() == 1 {
                "v as never"
            } else {
                "v"
            };
            let _ = writeln!(out, "      throw invalidVariant(\"{name}\", {v});");
            out.push_str("  }\n");
        }
    }
    out.push_str("}\n");
}

fn read_fn(out: &mut String, def: &TypeDef) {
    let name = def.name;
    let _ = writeln!(out, "function read{name}(r: Reader): {name} {{");
    match &def.kind {
        TypeKind::Struct(fields) => {
            out.push_str("  return {\n");
            for field in fields {
                let _ = writeln!(
                    out,
                    "    {}: {},",
                    ts_field_name(field.name),
                    read_expr(&field.ty)
                );
            }
            out.push_str("  };\n");
        }
        TypeKind::Newtype(inner) => {
            let _ = writeln!(out, "  return {};", read_expr(inner));
        }
        TypeKind::Enum(variants) => {
            out.push_str("  const variant = r.variant();\n");
            out.push_str("  switch (variant) {\n");
            for (index, variant) in variants.iter().enumerate() {
                let tag = variant.name;
                let _ = writeln!(out, "    case {index}:");
                match &variant.fields {
                    VariantFields::Unit => {
                        let _ = writeln!(out, "      return {{ type: \"{tag}\" }};");
                    }
                    VariantFields::Named(fields) if fields.is_empty() => {
                        let _ = writeln!(out, "      return {{ type: \"{tag}\" }};");
                    }
                    VariantFields::Newtype(inner) => {
                        let _ = writeln!(
                            out,
                            "      return {{ type: \"{tag}\", value: {} }};",
                            read_expr(inner)
                        );
                    }
                    VariantFields::Named(fields) => {
                        out.push_str("      return {\n");
                        let _ = writeln!(out, "        type: \"{tag}\",");
                        for field in fields {
                            let _ = writeln!(
                                out,
                                "        {}: {},",
                                ts_field_name(field.name),
                                read_expr(&field.ty)
                            );
                        }
                        out.push_str("      };\n");
                    }
                }
            }
            out.push_str("    default:\n");
            let _ = writeln!(out, "      throw r.unknownVariant(\"{name}\");");
            out.push_str("  }\n");
        }
    }
    out.push_str("}\n");
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn camel_case() {
        assert_eq!(ts_field_name("x"), "x");
        assert_eq!(ts_field_name("schema_hash"), "schemaHash");
        assert_eq!(ts_field_name("player_name"), "playerName");
        assert_eq!(ts_field_name("a_b_c"), "aBC");
    }

    #[test]
    fn type_mapping() {
        let opt = |t| TypeRef::Option(Box::new(t));
        let vec = |t| TypeRef::Vec(Box::new(t));
        assert_eq!(ts_type(&vec(opt(TypeRef::U8))), "(number | null)[]");
        assert_eq!(ts_type(&opt(vec(TypeRef::String))), "string[] | null");
        assert_eq!(ts_type(&vec(vec(TypeRef::Named("A")))), "A[][]");
        assert_eq!(rust_type_note(&opt(TypeRef::U8)), " // Option<u8>");
        assert_eq!(rust_type_note(&TypeRef::Named("NameId")), "");
        assert_eq!(ts_type(&opt(TypeRef::Fixed)), "Fixed | null");
        assert_eq!(rust_type_note(&TypeRef::Fixed), "");
        assert_eq!(write_expr(&TypeRef::Fixed, "v.rate", 0), "w.fixed(v.rate)");
        assert_eq!(read_expr(&TypeRef::Fixed), "r.fixed()");
    }

    #[test]
    fn nested_containers_use_distinct_item_names() {
        let ty = TypeRef::Vec(Box::new(TypeRef::Option(Box::new(TypeRef::U32))));
        assert_eq!(
            write_expr(&ty, "v.a", 0),
            "w.vec(v.a, (x) => w.option(x, (x1) => w.u32(x1)))"
        );
        assert_eq!(read_expr(&ty), "r.vec(() => r.option(() => r.u32()))");
    }

    #[test]
    fn files_have_headers_and_reserved_names_collide() {
        #[derive(tc_wire::Wire)]
        enum Msg {
            Moved { to: u32 },
            Bye,
        }
        let mut b = tc_wire::SchemaBuilder::new();
        b.root::<Msg>();
        let schema = b.finish().unwrap();
        let mut config = Config {
            sdk: Some(SdkConfig {
                root: "Msg".into(),
                events_path: "events.ts".into(),
                pass_path: "pass.ts".into(),
                pass: vec![Pass {
                    msg: "Moved".into(),
                    event: "moved".into(),
                    param: "x".into(),
                    payload: Payload::Field,
                    doc: "It moved.".into(),
                }],
                no_event: vec![("Bye".into(), "closes".into())],
                ..SdkConfig::default()
            }),
            ..Config::default()
        };
        let files = generate(&schema, &config).unwrap();
        let paths: Vec<&str> = files.iter().map(|(p, _)| p.as_str()).collect();
        assert_eq!(paths, ["generated.ts", "events.ts", "pass.ts"]);
        for (path, contents) in &files {
            assert!(contents.starts_with(&config.header), "{path}");
        }
        config.reserved.push("Msg".into());
        assert!(generate(&schema, &config).unwrap_err().contains("collides"));
    }

    #[test]
    fn maps_and_bytes() {
        let map = TypeRef::Map(Box::new(TypeRef::Named("NameId")), Box::new(TypeRef::U64));
        assert_eq!(ts_type(&map), "Map<NameId, number>");
        assert_eq!(
            write_expr(&map, "v.a", 0),
            "w.map(v.a, (k) => writeNameId(w, k), (x) => w.u64(x))"
        );
        assert_eq!(read_expr(&map), "r.map(() => readNameId(r), () => r.u64())");
        assert_eq!(
            ts_type_ref(&map),
            r#"{"map": [{"named": "NameId"}, "u64"]}"#
        );
        assert_eq!(ts_type(&TypeRef::Bytes), "Uint8Array");
        assert_eq!(ts_args_name("storage_view"), "StorageViewArgs");
        assert_eq!(ts_query_name("storage_view"), "storageView");
    }
}
