//! TypeScript for a game's clients, from its schema: [`generate_ts`],
//! [`define_schema_ts`] and [`define_schema_ts_with`].

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use tc_net::envelope::{
    AckMode, ClientSlot, Envelope, HelloField, Protocol, RejectedField, ServerSlot, WelcomeField,
};
use tc_sim::Game;
use tc_wire::schema::{Field, Schema, TypeKind, TypeRef, Variant, VariantFields};

/// Where [`generate_ts`] writes [`define_schema_ts`]'s module, under its
/// output directory.
pub const SCHEMA_TS: &str = "schema.ts";

/// The module a generated schema imports `defineSchema` from.
pub const NET_IMPORT: &str = "@thunderclap-engine/engine/net";

/// Writes the TypeScript tc-tsgen makes from `G`'s schema
/// ([`Game::schema`]) under `out`, by `config`, and [`define_schema_ts`]'s
/// module as [`SCHEMA_TS`]. Files whose text is already that are left
/// alone (so a watcher sees no change). The files written.
pub fn generate_ts<G: Game>(out: &Path, config: &tc_tsgen::Config) -> Result<Vec<PathBuf>, String> {
    let schema = G::schema();
    let mut files = tc_tsgen::generate(&schema, config)?;
    files.push((
        SCHEMA_TS.to_string(),
        define_schema_ts_with(&schema, NET_IMPORT, <G::Protocol as Protocol>::ENVELOPE)?,
    ));
    let mut written = Vec::new();
    for (rel, text) in files {
        let path = out.join(&rel);
        if std::fs::read_to_string(&path).is_ok_and(|old| old == text) {
            continue;
        }
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)
                .map_err(|e| format!("creating {}: {e}", parent.display()))?;
        }
        std::fs::write(&path, text).map_err(|e| format!("writing {}: {e}", path.display()))?;
        written.push(path);
    }
    Ok(written)
}

/// The envelope's own types, which `defineSchema` adds itself.
const ENVELOPE: [&str; 6] = [
    "ClientMsg",
    "ServerMsg",
    "Resume",
    "PatchOp",
    "PathStep",
    "Empty",
];

/// Where each role sits in the envelope: (message, variant, field; `""`
/// for a newtype variant).
const ROLES: [(&str, &str, &str, &str); 9] = [
    ("hello", "ClientMsg", "Hello", "ext"),
    ("command", "ClientMsg", "Command", "command"),
    ("interest", "ClientMsg", "SetInterest", "interest"),
    ("input", "ClientMsg", "Input", "input"),
    ("client", "ClientMsg", "Game", ""),
    ("welcome", "ServerMsg", "Welcome", "ext"),
    ("result", "ServerMsg", "CommandResult", "result"),
    ("state", "ServerMsg", "PlayerState", "state"),
    ("server", "ServerMsg", "Game", ""),
];

/// A TypeScript module that exports `schema`, the game's
/// `defineSchema(...)` (its types, roles, roots and queries, read off
/// `schema`), and `SCHEMA_HASH`, the hash both must have. `net_import`
/// is the module `defineSchema` comes from. An error: `schema` is not a
/// game schema (no envelope).
pub fn define_schema_ts(schema: &Schema, net_import: &str) -> Result<String, String> {
    define_schema_ts_with(schema, net_import, &Envelope::ENGINE)
}

/// [`define_schema_ts`] for a protocol laid out by `envelope`
/// (`Protocol::ENVELOPE`): with `defineSchema`'s `envelope` spec when it is
/// not the engine's. Every [`Envelope`] option has its TypeScript form: the
/// slots, `Hello`'s fields (a `Hello` whose game fields sit among the
/// envelope's, [`HelloField::ExtFields`], gives a struct of those fields as
/// `roles.hello` and `{ ext: n }` entries), `Welcome`'s and `Rejected`'s
/// fields, the `Ack` ([`AckMode`]) and the close enum. `client_text` is
/// only the server's words, so it has none.
///
/// An error: `schema` is not a game schema, or its envelope messages are
/// not what `envelope` lays out (each mismatch named), so the TypeScript
/// schema could not have the same hash.
pub fn define_schema_ts_with(
    schema: &Schema,
    net_import: &str,
    envelope: &Envelope,
) -> Result<String, String> {
    let engine = envelope.is_engine();
    let find = |name: &str| schema.types().iter().find(|t| t.name == name);
    let split = if engine {
        None
    } else {
        check_envelope(schema, envelope)?;
        split_hello(schema, envelope)?
    };
    let mut out = String::new();
    out.push_str("// Generated by thunderclap-server from the game's Rust types. Do not edit.\n");
    let _ = writeln!(
        out,
        "import {{ defineSchema }} from {};\n",
        js_str(net_import)
    );
    out.push_str("/** The schema's hash: the server's, which `schema` must match. */\n");
    let _ = writeln!(
        out,
        "export const SCHEMA_HASH = {};\n",
        js_str(&schema.hash())
    );
    out.push_str("/** The game's wire schema, inside the engine envelope. */\n");
    out.push_str("export const schema = defineSchema({\n  types: {\n");
    for t in schema.types() {
        if ENVELOPE.contains(&t.name) {
            continue;
        }
        let def = match &t.kind {
            TypeKind::Struct(fields) => format!("{{ struct: {} }}", fields_ts(fields)),
            TypeKind::Newtype(ty) => format!("{{ newtype: {} }}", type_ts(ty)),
            TypeKind::Enum(variants) => {
                let vs: Vec<String> = variants.iter().map(variant_ts).collect();
                format!("{{ enum: {{ {} }} }}", vs.join(", "))
            }
        };
        let _ = writeln!(out, "    {}: {def},", key(t.name));
    }
    if let Some((name, fields)) = &split {
        let _ = writeln!(
            out,
            "    {}: {{ struct: {} }},",
            key(name),
            fields_ts(fields)
        );
    }
    out.push_str("  },\n  roles: {\n");
    for (role, msg, variant, field) in ROLES {
        if role == "hello"
            && let Some((name, _)) = &split
        {
            let _ = writeln!(out, "    hello: {},", js_str(name));
            continue;
        }
        let def = find(msg).ok_or_else(|| format!("no {msg}: not a game schema"))?;
        let TypeKind::Enum(variants) = &def.kind else {
            return Err(format!("{msg} is not an enum"));
        };
        let Some(v) = variants.iter().find(|v| v.name == variant) else {
            // A protocol of its own may leave the message off its wire.
            if engine {
                return Err(format!("no {msg}::{variant}"));
            }
            continue;
        };
        let ty = match (&v.fields, field) {
            (VariantFields::Newtype(ty), "") => ty,
            (VariantFields::Named(fields), f) => {
                &fields
                    .iter()
                    .find(|x| x.name == f)
                    .ok_or_else(|| format!("no {msg}::{variant}.{f}"))?
                    .ty
            }
            _ => return Err(format!("{msg}::{variant} has an unexpected shape")),
        };
        if *ty != TypeRef::Named("Empty") {
            let _ = writeln!(out, "    {role}: {},", type_ts(ty));
        }
    }
    out.push_str("  },\n  roots: [");
    let roots: Vec<String> = schema
        .roots()
        .iter()
        .filter(|r| !ENVELOPE.contains(r))
        .map(|r| js_str(r))
        .collect();
    out.push_str(&roots.join(", "));
    out.push_str("],\n");
    if !engine {
        out.push_str(&envelope_ts(schema, envelope)?);
    }
    out.push_str("  queries: {\n");
    for q in schema.queries() {
        let args = if q.args.is_empty() {
            String::new()
        } else {
            format!("args: {}, ", fields_ts(&q.args))
        };
        let _ = writeln!(
            out,
            "    {}: {{ {args}result: {} }},",
            key(q.name),
            type_ts(&q.result)
        );
    }
    out.push_str("  },\n});\n");
    Ok(out)
}

/// The variants of the schema's envelope enum `msg`.
fn envelope_variants<'a>(schema: &'a Schema, msg: &str) -> Result<&'a [Variant], String> {
    match schema.types().iter().find(|t| t.name == msg) {
        Some(t) => match &t.kind {
            TypeKind::Enum(v) => Ok(v),
            _ => Err(format!("{msg} is not an enum")),
        },
        None => Err(format!("no {msg}: not a game schema")),
    }
}

/// The fields of `v`, by name (none for a unit or newtype variant).
fn field_names(v: &Variant) -> Vec<&'static str> {
    match &v.fields {
        VariantFields::Named(f) => f.iter().map(|f| f.name).collect(),
        _ => Vec::new(),
    }
}

/// `Hello`'s field names as `envelope` lays them out, `None` standing for
/// each of the game's fields.
fn hello_names(envelope: &Envelope) -> Vec<Option<&'static str>> {
    let mut out = Vec::new();
    for f in envelope.hello {
        match f {
            HelloField::Token => out.push(Some("token")),
            HelloField::SchemaHash => out.push(Some("schema_hash")),
            HelloField::Bulk => out.push(Some("bulk")),
            HelloField::Ext => out.push(Some("ext")),
            HelloField::ExtFields(n) => out.extend((0..*n).map(|_| None)),
        }
    }
    out
}

fn welcome_name(f: WelcomeField) -> &'static str {
    match f {
        WelcomeField::Player => "player",
        WelcomeField::Time => "time",
        WelcomeField::Paused => "paused",
        WelcomeField::StepUs => "step_us",
        WelcomeField::Ext => "ext",
    }
}

fn rejected_name(f: RejectedField) -> &'static str {
    match f {
        RejectedField::Reason => "reason",
        RejectedField::StaleSchema => "stale_schema",
    }
}

/// The fields an engine client message has on `envelope`'s wire (`None`:
/// `Hello`, or the game's).
fn client_fields(slot: ClientSlot, envelope: &Envelope) -> Option<Vec<&'static str>> {
    Some(match slot {
        ClientSlot::Command => vec!["seq", "command"],
        ClientSlot::Subscribe => vec!["sub", "query", "args", "resume"],
        ClientSlot::Unsubscribe => vec!["sub"],
        ClientSlot::Ping => vec!["client_time"],
        ClientSlot::SetInterest => vec!["interest"],
        ClientSlot::Input => vec!["seq", "input"],
        ClientSlot::TakeControl | ClientSlot::EntityResync => Vec::new(),
        ClientSlot::Ack => vec![envelope.ack.field()],
        ClientSlot::Hello | ClientSlot::Game | ClientSlot::Inline => return None,
    })
}

/// The fields an engine server message has on `envelope`'s wire (`None`:
/// the game's).
fn server_fields(slot: ServerSlot, envelope: &Envelope) -> Option<Vec<&'static str>> {
    Some(match slot {
        ServerSlot::Welcome => envelope.welcome.iter().map(|f| welcome_name(*f)).collect(),
        ServerSlot::Rejected => envelope
            .rejected
            .iter()
            .map(|f| rejected_name(*f))
            .collect(),
        ServerSlot::CommandResult => vec!["seq", "result"],
        ServerSlot::Update => vec!["sub", "version", "hash", "patch"],
        ServerSlot::Resync => vec!["sub", "version", "hash", "result"],
        ServerSlot::QueryFailed => vec!["sub", "reason"],
        ServerSlot::Clock => vec!["time", "paused"],
        ServerSlot::Pong => vec!["client_time", "time", "paused"],
        ServerSlot::InterestRejected => vec!["reason"],
        ServerSlot::EntityStream => vec!["data"],
        ServerSlot::PlayerState => vec!["seq", "state", "tick_us"],
        ServerSlot::Control => vec!["driving"],
        ServerSlot::Closed => vec!["code", "reason"],
        ServerSlot::Bulk => vec!["codec", "data"],
        ServerSlot::Game | ServerSlot::Inline => return None,
    })
}

/// Checks that the schema's `ClientMsg` and `ServerMsg` are what
/// `envelope` lays out: a variant for each slot, each engine message under
/// its own name with its fields. Every mismatch, in one error.
fn check_envelope(schema: &Schema, envelope: &Envelope) -> Result<(), String> {
    let mut wrong = Vec::new();
    let mut check =
        |msg: &str, vs: &[Variant], slots: Vec<(&'static str, Option<Vec<&'static str>>)>| {
            if vs.len() != slots.len() {
                wrong.push(format!(
                    "{msg} has {} variants, the envelope {} slots",
                    vs.len(),
                    slots.len()
                ));
            }
            for (v, (name, fields)) in vs.iter().zip(slots) {
                if name.is_empty() {
                    continue; // The game's own (inline).
                }
                if v.name != name {
                    wrong.push(format!("{msg}::{} where the envelope has {name}", v.name));
                    continue;
                }
                let Some(fields) = fields else { continue };
                let have = field_names(v);
                if have != fields {
                    wrong.push(format!(
                        "{msg}::{name} has fields [{}], the envelope's are [{}]",
                        have.join(", "),
                        fields.join(", ")
                    ));
                }
            }
        };
    let client = envelope_variants(schema, "ClientMsg")?;
    let client_slots = envelope
        .client
        .iter()
        .map(|s| match s {
            ClientSlot::Inline => ("", None),
            s => (client_slot(*s), client_fields(*s, envelope)),
        })
        .collect();
    check("ClientMsg", client, client_slots);
    let server = envelope_variants(schema, "ServerMsg")?;
    let server_slots = envelope
        .server
        .iter()
        .map(|s| match s {
            ServerSlot::Inline => ("", None),
            s => (server_slot(*s), server_fields(*s, envelope)),
        })
        .collect();
    check("ServerMsg", server, server_slots);
    if let Some(hello) = client.iter().find(|v| v.name == "Hello") {
        let have = field_names(hello);
        let want = hello_names(envelope);
        let fits = have.len() == want.len()
            && have
                .iter()
                .zip(&want)
                .all(|(h, w)| w.is_none_or(|w| w == *h));
        if !fits {
            let want: Vec<&str> = want.iter().map(|w| w.unwrap_or("<game>")).collect();
            wrong.push(format!(
                "ClientMsg::Hello has fields [{}], the envelope's are [{}]",
                have.join(", "),
                want.join(", ")
            ));
        }
    }
    if wrong.is_empty() {
        Ok(())
    } else {
        Err(format!(
            "the schema's envelope is not the one laid out: {}",
            wrong.join("; ")
        ))
    }
}

/// For a `Hello` carrying the game's fields as its own
/// ([`HelloField::ExtFields`]): a name no type of the schema has, and those
/// fields, the struct `roles.hello` names.
fn split_hello(
    schema: &Schema,
    envelope: &Envelope,
) -> Result<Option<(String, Vec<Field>)>, String> {
    if !envelope
        .hello
        .iter()
        .any(|f| matches!(f, HelloField::ExtFields(_)))
    {
        return Ok(None);
    }
    let client = envelope_variants(schema, "ClientMsg")?;
    let hello = client
        .iter()
        .find(|v| v.name == "Hello")
        .ok_or("no ClientMsg::Hello")?;
    let VariantFields::Named(fields) = &hello.fields else {
        return Err("ClientMsg::Hello has no named fields".into());
    };
    let game: Vec<Field> = fields
        .iter()
        .zip(hello_names(envelope))
        .filter(|(_, name)| name.is_none())
        .map(|(f, _)| f.clone())
        .collect();
    let taken = |n: &str| ENVELOPE.contains(&n) || schema.types().iter().any(|t| t.name == n);
    let name = std::iter::once("Hello".to_string())
        .chain((0..).map(|i| format!("Hello{i}")))
        .find(|n| !taken(n))
        .expect("a free name");
    Ok(Some((name, game)))
}

/// `defineSchema`'s `envelope` spec for `envelope`, the game's inline
/// messages read off `schema`.
fn envelope_ts(schema: &Schema, envelope: &Envelope) -> Result<String, String> {
    let slots = |vs: &[Variant], engine: Vec<Option<&'static str>>| -> Vec<String> {
        vs.iter()
            .zip(engine)
            .map(|(v, name)| match name {
                Some(name) => js_str(name),
                None => format!("{{ {} }}", variant_ts(v)),
            })
            .collect()
    };
    let client = envelope_variants(schema, "ClientMsg")?;
    let server = envelope_variants(schema, "ServerMsg")?;
    let client_names = envelope
        .client
        .iter()
        .map(|s| (*s != ClientSlot::Inline).then(|| client_slot(*s)))
        .collect();
    let server_names = envelope
        .server
        .iter()
        .map(|s| (*s != ServerSlot::Inline).then(|| server_slot(*s)))
        .collect();
    let hello: Vec<String> = envelope
        .hello
        .iter()
        .map(|f| match f {
            HelloField::Token => js_str("token"),
            HelloField::SchemaHash => js_str("schema_hash"),
            HelloField::Bulk => js_str("bulk"),
            HelloField::Ext => js_str("ext"),
            HelloField::ExtFields(n) => format!("{{ ext: {n} }}"),
        })
        .collect();
    let welcome: Vec<String> = envelope
        .welcome
        .iter()
        .map(|f| js_str(welcome_name(*f)))
        .collect();
    let mut out = String::from("  envelope: {\n");
    let _ = writeln!(
        out,
        "    client: [{}],",
        slots(client, client_names).join(", ")
    );
    let _ = writeln!(
        out,
        "    server: [{}],",
        slots(server, server_names).join(", ")
    );
    let _ = writeln!(out, "    hello: [{}],", hello.join(", "));
    let _ = writeln!(out, "    welcome: [{}],", welcome.join(", "));
    if envelope.rejected != Envelope::ENGINE.rejected {
        let rejected: Vec<String> = envelope
            .rejected
            .iter()
            .map(|f| js_str(rejected_name(*f)))
            .collect();
        let _ = writeln!(out, "    rejected: [{}],", rejected.join(", "));
    }
    match envelope.ack {
        AckMode::Each => {}
        AckMode::Total => out.push_str("    ack: 'total',\n"),
        AckMode::Messages => out.push_str("    ack: 'messages',\n"),
    }
    if let Some(close) = &envelope.close {
        let ty = server
            .iter()
            .find(|v| v.name == "Closed")
            .and_then(|v| match &v.fields {
                VariantFields::Named(f) => f.iter().find(|f| f.name == "code"),
                _ => None,
            })
            .map(|f| &f.ty);
        let Some(TypeRef::Named(ty)) = ty else {
            return Err("ServerMsg::Closed has no close enum".into());
        };
        let codes: Vec<String> = close.codes.iter().map(u16::to_string).collect();
        let _ = writeln!(
            out,
            "    close: {{ type: {}, codes: [{}] }},",
            js_str(ty),
            codes.join(", ")
        );
    }
    out.push_str("  },\n");
    Ok(out)
}

fn client_slot(slot: ClientSlot) -> &'static str {
    match slot {
        ClientSlot::Hello => "Hello",
        ClientSlot::Command => "Command",
        ClientSlot::Subscribe => "Subscribe",
        ClientSlot::Unsubscribe => "Unsubscribe",
        ClientSlot::Ping => "Ping",
        ClientSlot::SetInterest => "SetInterest",
        ClientSlot::Input => "Input",
        ClientSlot::TakeControl => "TakeControl",
        ClientSlot::EntityResync => "EntityResync",
        ClientSlot::Ack => "Ack",
        ClientSlot::Game | ClientSlot::Inline => "Game",
    }
}

fn server_slot(slot: ServerSlot) -> &'static str {
    match slot {
        ServerSlot::Welcome => "Welcome",
        ServerSlot::Rejected => "Rejected",
        ServerSlot::CommandResult => "CommandResult",
        ServerSlot::Update => "Update",
        ServerSlot::Resync => "Resync",
        ServerSlot::QueryFailed => "QueryFailed",
        ServerSlot::Clock => "Clock",
        ServerSlot::Pong => "Pong",
        ServerSlot::InterestRejected => "InterestRejected",
        ServerSlot::EntityStream => "EntityStream",
        ServerSlot::PlayerState => "PlayerState",
        ServerSlot::Control => "Control",
        ServerSlot::Closed => "Closed",
        ServerSlot::Bulk => "Bulk",
        ServerSlot::Game | ServerSlot::Inline => "Game",
    }
}

/// One enum variant as `defineSchema` takes it: `Name: body`.
fn variant_ts(v: &Variant) -> String {
    let body = match &v.fields {
        VariantFields::Unit => "null".to_string(),
        VariantFields::Named(f) => fields_ts(f),
        VariantFields::Newtype(ty) => format!("[{}]", type_ts(ty)),
    };
    format!("{}: {body}", key(v.name))
}

fn fields_ts(fields: &[Field]) -> String {
    let fs: Vec<String> = fields
        .iter()
        .map(|f| format!("{}: {}", key(f.name), type_ts(&f.ty)))
        .collect();
    format!("{{ {} }}", fs.join(", "))
}

fn type_ts(ty: &TypeRef) -> String {
    match ty {
        TypeRef::Vec(t) => format!("{{ vec: {} }}", type_ts(t)),
        TypeRef::Option(t) => format!("{{ option: {} }}", type_ts(t)),
        TypeRef::Map(k, v) => format!("{{ map: [{}, {}] }}", type_ts(k), type_ts(v)),
        TypeRef::Named(n) => js_str(n),
        scalar => js_str(&scalar.to_string()),
    }
}

/// An object key: bare when it is an identifier.
fn key(name: &str) -> String {
    let ident = name
        .chars()
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_');
    if ident {
        name.to_string()
    } else {
        js_str(name)
    }
}

fn js_str(s: &str) -> String {
    let mut out = String::from("'");
    for c in s.chars() {
        match c {
            '\'' | '\\' => {
                out.push('\\');
                out.push(c);
            }
            '\n' => out.push_str("\\n"),
            c => out.push(c),
        }
    }
    out.push('\'');
    out
}

#[cfg(test)]
mod tests {
    use tc_net::Empty;
    use tc_net::envelope::{CloseCodes, HelloField, WelcomeField};
    use tc_wire::Wire;

    use super::*;

    #[derive(Debug, Clone, PartialEq)]
    struct Own;

    #[derive(Wire, Debug, Clone, PartialEq)]
    enum Talk {
        Say { text: String },
    }

    #[derive(Wire, Debug, Clone, PartialEq)]
    enum Bye {
        Restart,
        Kicked,
    }

    impl Protocol for Own {
        type Hello = String;
        type Welcome = Empty;
        type Command = u32;
        type Result = String;
        type Interest = Empty;
        type Input = Empty;
        type State = Empty;
        type Client = Talk;
        type Server = String;
        const ENVELOPE: &'static Envelope = &Envelope {
            client: &[
                ClientSlot::Ping,
                ClientSlot::Hello,
                ClientSlot::Inline,
                ClientSlot::Ack,
            ],
            server: &[
                ServerSlot::Welcome,
                ServerSlot::Pong,
                ServerSlot::Rejected,
                ServerSlot::Closed,
                ServerSlot::Game,
            ],
            hello: &[HelloField::SchemaHash, HelloField::Token, HelloField::Ext],
            welcome: &[
                WelcomeField::Player,
                WelcomeField::Time,
                WelcomeField::Paused,
                WelcomeField::Ext,
            ],
            ack: AckMode::Total,
            close: Some(CloseCodes {
                describe: <Bye as Wire>::describe,
                codes: &[1012, 4003],
            }),
            ..Envelope::ENGINE
        };
    }

    #[test]
    fn a_protocol_of_its_own_gets_an_envelope_spec() {
        let schema = tc_net::schema_builder::<Own>().finish().unwrap();
        let ts = define_schema_ts_with(&schema, NET_IMPORT, Own::ENVELOPE).unwrap();
        for line in [
            "    Bye: { enum: { Restart: null, Kicked: null } },\n",
            "    hello: 'String',\n    server: 'String',\n",
            "    client: ['Ping', 'Hello', { Say: { text: 'String' } }, 'Ack'],\n",
            "    server: ['Welcome', 'Pong', 'Rejected', 'Closed', 'Game'],\n",
            "    hello: ['schema_hash', 'token', 'ext'],\n",
            "    welcome: ['player', 'time', 'paused', 'ext'],\n",
            "    ack: 'total',\n",
            "    close: { type: 'Bye', codes: [1012, 4003] },\n",
        ] {
            assert!(ts.contains(line), "{line}in\n{ts}");
        }
        assert!(!ts.contains("command:"), "Command is off this wire:\n{ts}");
    }
}
